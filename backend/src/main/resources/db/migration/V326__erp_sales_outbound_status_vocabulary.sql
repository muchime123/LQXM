-- =====================================================================
-- 销售出库单状态词表：镜像单「沿用氚云原状态」，与「过账」语义脱钩
-- ---------------------------------------------------------------------
-- 背景（LQ 2026-09-22 拍板）：
--   V324 当初把 18,966 张氚云镜像单一律落成 `DRAFT`（草稿），理由是
--   `POSTED` 的语义是「扣减当前库存」，而历史单扣当前库存会把库存冲成负数。
--   副作用是：**业务侧看到的全是「草稿」**，而它们在氚云里明明是「已生效」的事实单 ——
--   页面上读不出「这单到底生没生效」。
--
--   拍板口径：**镜像单的 status 沿用氚云原状态**；
--   「是否已过账 / 过账会不会扣库存」属于**另一套设计**（待商榷），
--   本阶段不涉及、也不与镜像状态耦合。
--
-- 实测氚云源状态分布（2026-09-22，真库 sales_outbounds 全量 18,966 张）：
--   已生效 18,813 / 草稿 111 / 进行中 42
--
-- 词表（status 列口径）：
--   DRAFT       草稿     —— ERP 自建单的初始态；也是氚云「草稿」的镜像态
--   CONFIRMED   已生效   —— 氚云「已生效」镜像态。⭐ **非库存态：不代表已过账、不动库存**
--   PROCESSING  进行中   —— 氚云「进行中」镜像态。非库存态
--   CANCELLED   已取消   —— 氚云「已取消」镜像态。非库存态
--   POSTED      已过账   —— **仅 ERP 自建单**的过账流程使用（扣库存 + 写流水）
--   REVERSED    已冲销   —— 仅 ERP 自建单；冲销回补库存，终态
--
-- ⚠️ 词表**来源**是台账侧既有的归一器
--   （`SalesOutboundSettlementService.normalizeOutboundStatus`，覆盖
--   「生效/完结/生产中/加工中/取消…」等同义写法，`SalesOutboundSettlementServiceTest` 已钉死）。
--   本迁移**刻意不新造词**：同一个源字段在页面两处显示成不同的词，比兜底方向的取舍危险得多。
--
-- ⚠️ 三个为什么：
--   ① 为什么不把氚云状态原文直接塞进 status：一个字段同时表达「事实状态」与「过账状态」，
--      正是本项目反复吃过亏的写法（参见 `audit_logs.entity_type` 一个字段扛两件事导致的撞名事故）。
--      原文另有 `source_status_raw` 一列忠实留存。
--   ② 为什么不映射成 POSTED：POSTED = 扣减**当前**库存，而这批单是 2025-11~2026-09
--      已发生的事实，直接落 POSTED 会在镜像瞬间把当前库存冲成巨额负数。
--   ③ 本迁移**不含任何数据/映射语句**：映射只有 Java 一份实现
--      （`H3SalesOutboundMirrorService.businessStatus`），
--      历史行回填也走同一函数（`repairMirroredStatuses`），避免「Java 一份口径 + SQL 一份口径」漂移。
-- =====================================================================

ALTER TABLE erp_sales_outbounds
    MODIFY COLUMN status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        COMMENT '业务状态：DRAFT 草稿 / CONFIRMED 已生效 / PROCESSING 进行中 / CANCELLED 已取消 / POSTED 已过账 / REVERSED 已冲销。⚠️ CONFIRMED、PROCESSING、CANCELLED 是氚云镜像单的原状态（词表与映射复用台账归一器），属非库存态——不代表已过账、不影响库存；POSTED/REVERSED 仅服务 ERP 自建单的过账流程';
