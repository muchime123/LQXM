-- 密码管理模块
-- 分类表
CREATE TABLE IF NOT EXISTS password_categories (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- 密码条目表（密码字段 AES-256-GCM 加密存储）
CREATE TABLE IF NOT EXISTS password_entries (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    category_id BIGINT NOT NULL,
    platform VARCHAR(200) COMMENT '平台/设备/网站名称',
    url VARCHAR(500) COMMENT '登录地址',
    account VARCHAR(300) COMMENT '账号/用户名/邮箱',
    password_encrypted TEXT COMMENT 'AES-256-GCM 加密后的密码（Base64编码）',
    notes VARCHAR(500) COMMENT '备注',
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_password_entry_category FOREIGN KEY (category_id) REFERENCES password_categories(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

