CREATE TABLE office_assets (
    id BIGINT NOT NULL AUTO_INCREMENT,
    asset_code VARCHAR(40) NOT NULL,
    name VARCHAR(120) NOT NULL,
    category VARCHAR(60) NOT NULL,
    brand VARCHAR(80) NULL,
    model VARCHAR(100) NULL,
    serial_number VARCHAR(120) NULL,
    department VARCHAR(100) NULL,
    custodian VARCHAR(100) NULL,
    location VARCHAR(160) NULL,
    status VARCHAR(30) NOT NULL DEFAULT '在库',
    purchase_date DATE NULL,
    purchase_price DECIMAL(12, 2) NULL,
    supplier VARCHAR(160) NULL,
    warranty_until DATE NULL,
    notes VARCHAR(1000) NULL,
    last_inventory_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_office_asset_code (asset_code),
    KEY idx_office_asset_category (category),
    KEY idx_office_asset_status (status),
    KEY idx_office_asset_department (department),
    KEY idx_office_asset_custodian (custodian)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE office_asset_records (
    id BIGINT NOT NULL AUTO_INCREMENT,
    asset_id BIGINT NOT NULL,
    action VARCHAR(30) NOT NULL,
    operator_name VARCHAR(100) NULL,
    department VARCHAR(100) NULL,
    custodian VARCHAR(100) NULL,
    location VARCHAR(160) NULL,
    notes VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_office_asset_record_asset (asset_id),
    KEY idx_office_asset_record_created (created_at),
    CONSTRAINT fk_office_asset_record_asset FOREIGN KEY (asset_id) REFERENCES office_assets (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
