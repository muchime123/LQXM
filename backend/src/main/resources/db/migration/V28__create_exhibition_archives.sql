CREATE TABLE exhibition_archives (
    id BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(200) NOT NULL,
    edition VARCHAR(80),
    start_date DATE,
    end_date DATE,
    city VARCHAR(100),
    venue VARCHAR(200),
    address VARCHAR(300),
    booth_number VARCHAR(80),
    booth_area VARCHAR(80),
    organizer VARCHAR(200),
    contractor VARCHAR(200),
    theme VARCHAR(200),
    industry VARCHAR(200),
    status VARCHAR(60),
    lead_owner VARCHAR(100),
    total_budget DECIMAL(12,2),
    actual_cost DECIMAL(12,2),
    expected_deal_amount DECIMAL(12,2),
    visitor_count INT,
    valid_lead_count INT,
    a_lead_count INT,
    b_lead_count INT,
    c_lead_count INT,
    quote_count INT,
    sample_count INT,
    deal_count INT,
    next_follow_up_date DATE,
    tags VARCHAR(500),
    participants LONGTEXT,
    traffic_hotel_logistics LONGTEXT,
    contract_files LONGTEXT,
    booth_design_materials LONGTEXT,
    exhibited_equipment LONGTEXT,
    packaging_materials LONGTEXT,
    application_scenarios LONGTEXT,
    photo_materials LONGTEXT,
    video_materials LONGTEXT,
    customer_inquiries LONGTEXT,
    customer_raw_needs LONGTEXT,
    competitor_insights LONGTEXT,
    promotion_records LONGTEXT,
    expense_records LONGTEXT,
    material_inventory LONGTEXT,
    review_summary LONGTEXT,
    follow_up_tasks LONGTEXT,
    improvement_actions LONGTEXT,
    attachments LONGTEXT,
    notes LONGTEXT,
    deleted_at DATETIME,
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    INDEX idx_exhibition_status (status),
    INDEX idx_exhibition_city (city),
    INDEX idx_exhibition_start_date (start_date),
    INDEX idx_exhibition_lead_owner (lead_owner)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
