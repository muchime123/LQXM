-- 官网独立公司介绍草稿；不从内部公司档案自动复制或发布。
CREATE TABLE website_company_profiles (
    id BIGINT NOT NULL PRIMARY KEY,
    company_name VARCHAR(300) NOT NULL,
    company_name_en VARCHAR(300),
    brand_name VARCHAR(200),
    brand_name_en VARCHAR(200),
    brand_slogan VARCHAR(500),
    mission TEXT,
    vision TEXT,
    company_values TEXT,
    core_positioning TEXT,
    main_business TEXT,
    target_industries TEXT,
    advantages TEXT,
    manufacturing_strengths TEXT,
    enterprise_scale VARCHAR(200),
    establishment_date DATE,
    office_address VARCHAR(500),
    factory_address VARCHAR(500),
    phone VARCHAR(100),
    email VARCHAR(200),
    website VARCHAR(500),
    logo_media_id BIGINT,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    published_at DATETIME,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_website_company_logo FOREIGN KEY (logo_media_id) REFERENCES website_media_assets(id),
    CONSTRAINT chk_website_company_status CHECK (status IN ('DRAFT', 'PUBLISHED'))
);
